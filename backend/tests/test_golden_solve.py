"""Golden solve cases: the solver against hand worksheets in evals/golden/solve/ (1 % tolerance).

K values are computed here from the case geometry with app.solver.k_methods (as the resolve step
would), then solved. A table (case, item, expected, got, error %) is printed at the end of the
module and written to evals/golden/solve/RESULTS.md.
"""

from __future__ import annotations

import contextlib
import json

import pytest

from app.core.config import get_settings
from app.schema.solve import FluidProps, Provenanced, SegmentInput
from app.solver import (
    SOLVER_VERSION,
    bend_k,
    solve_forward,
    solve_inverse,
    transition_k,
    valve_k_from_cv,
)

SOLVE_DIR = get_settings().evals_dir / "golden" / "solve"
CASES = sorted(p.name.removesuffix(".solve.json") for p in SOLVE_DIR.glob("*.solve.json"))
REL = 0.01

pytestmark = pytest.mark.skipif(not CASES, reason="golden solve cases not mounted")


@pytest.fixture(scope="module")
def table(request):
    rows: list[tuple[str, str, float, float]] = []
    yield rows
    if not rows:
        return
    lines = [
        "# Golden solve results",
        "",
        "Generated by backend/tests/test_golden_solve.py against the hand worksheets "
        f"(tolerance {REL:.0%}). Solver {SOLVER_VERSION}. Status: pending review by Rohith.",
        "",
        "| case | item | expected | got | error % | result |",
        "|---|---|---:|---:|---:|---|",
    ]
    for case, item, exp, got in rows:
        err = abs(got - exp) / abs(exp) * 100
        lines.append(
            f"| {case} | {item} | {exp:.6g} | {got:.6g} | {err:.4f} "
            f"| {'PASS' if err <= REL * 100 else 'FAIL'} |"
        )
    with contextlib.suppress(OSError):
        (SOLVE_DIR / "RESULTS.md").write_text("\n".join(lines) + "\n")
    capman = request.config.pluginmanager.getplugin("capturemanager")
    reporter = request.config.pluginmanager.getplugin("terminalreporter")
    if reporter is not None and capman is not None:
        with capman.global_and_fixture_disabled():
            reporter.write_line("")
            for line in lines[4:]:
                reporter.write_line(line)


def load(case: str) -> tuple[dict, list[SegmentInput], FluidProps, float]:
    data = json.loads((SOLVE_DIR / f"{case}.solve.json").read_text())
    fl = data["fluid"]
    fluid = FluidProps(
        name=fl["name"],
        density_kg_m3=Provenanced(value=fl["density_kg_m3"], unit="kg/m^3", source=fl["source"]),
        viscosity_pa_s=Provenanced(value=fl["viscosity_pa_s"], unit="Pa*s", source=fl["source"]),
    )
    e = data["material"]["roughness_m"]
    segs = []
    for s in data["segments"]:
        k = None
        if s["type"] == "bend":
            k = bend_k(s["angle_deg"], s["r_over_d"], s["d_m"], e)
        elif s["type"] == "transition":
            k = transition_k(s["d_in_m"], s["d_out_m"], s["half_angle_deg"], s["kind"])
        elif s["type"] == "valve":
            k = valve_k_from_cv(s["cv"], s["d_m"])
        segs.append(
            SegmentInput(
                component_id=s["component_id"],
                type=s["type"],
                d_m=s["d_m"],
                length_m=s["length_m"],
                k=k and k.value,
                k_ref_d_m=k and s["d_m"],
                k_source=k and k.source,
                k_match=k and "computed",
            )
        )
    return data, segs, fluid, e


@pytest.mark.parametrize("case", CASES)
def test_golden_forward(case: str, table) -> None:
    data, segs, fluid, e = load(case)
    r = solve_forward(segs, fluid, e, data["mdot_kg_s"])
    assert r.status == "complete"
    checks = []
    for exp, seg, got in zip(data["segments"], segs, r.segments, strict=True):
        if "expected_k" in exp:
            checks.append((f"{seg.component_id} {seg.type} K", exp["expected_k"], got.k))
        checks.append((f"{seg.component_id} {seg.type} dp Pa", exp["expected_dp_pa"], got.dp_pa))
    checks.append(("total dp Pa", data["expected_total_dp_pa"], r.total_dp_pa))
    for item, exp, got in checks:
        table.append((case, item, exp, got))
    for item, exp, got in checks:
        assert got == pytest.approx(exp, rel=REL), item


@pytest.mark.parametrize("case", [c for c in CASES if c.startswith("07")])
def test_golden_inverse(case: str, table) -> None:
    data, segs, fluid, e = load(case)
    inv = data["inverse"]
    r = solve_inverse(segs, fluid, e, inv["dp_target_pa"])
    table.append((case, "inverse mdot kg/s", inv["expected_mdot_kg_s"], r.mdot_kg_s))
    assert r.status == "complete" and r.mode == "flow"
    assert r.mdot_kg_s == pytest.approx(inv["expected_mdot_kg_s"], rel=REL)
    assert r.total_dp_pa == pytest.approx(inv["dp_target_pa"], rel=1e-9)
