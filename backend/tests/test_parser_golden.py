def _parse(parsed: dict[str, ParseOutput], case: str) -> ParseOutput:
    if case not in parsed:
        parsed[case] = parse_file(GOLDEN / f"{case}.step")
    return parsed[case]


# --------------------------------------------------------------------------- comparison
def _rel(found: float, exp: float) -> float:
    return abs(found - exp) / abs(exp) if exp else abs(found)


def _compare_component(exp: dict, got: dict, errs: list[str], where: str) -> float:
    """Append mismatches to errs; return the max relative length error (fraction)."""
    max_err = 0.0
    if got["type"] != exp["type"]:
        errs.append(f"{where}: type {got['type']} != {exp['type']}")
        return max_err

    def length(key: str, gkey: str | None = None) -> None:
        nonlocal max_err
        e = _rel(got[gkey or key], exp[key])
        max_err = max(max_err, e)
        if e > LEN_REL:
            errs.append(f"{where}: {key} {got[gkey or key]:.6f} != {exp[key]:.6f} ({e:.2%})")

    def diam(key: str) -> None:
        if abs(got[key] - exp[key]) > DIAM_ABS:
            errs.append(f"{where}: {key} {got[key]:.6f} != {exp[key]:.6f}")

    def angle(key: str) -> None:
        if abs(got[key] - exp[key]) > ANGLE_ABS:
            errs.append(f"{where}: {key} {got[key]:.3f} != {exp[key]:.3f}")

    t = exp["type"]
    if t == "pipe":
        diam("inner_diameter_m")
        length("length_m")
    elif t == "bend":
        diam("inner_diameter_m")
        angle("angle_deg")
        length("bend_radius_m")
        if _rel(got["r_over_d"], exp["r_over_d"]) > LEN_REL:
            errs.append(f"{where}: r_over_d {got['r_over_d']} != {exp['r_over_d']}")
    elif t == "transition":
        diam("d_in_m")
        diam("d_out_m")
        length("length_m")
        angle("half_angle_deg")
        if got["kind"] != exp["kind"]:
            errs.append(f"{where}: kind {got['kind']} != {exp['kind']}")
    elif t == "valve":
        for k in ("name", "part_path", "vendor", "valve_type", "cv"):
            if got[k] != exp[k]:
                errs.append(f"{where}: {k} {got[k]!r} != {exp[k]!r}")
    elif t == "unclassified":
        for k in ("name", "part_path"):
            if got[k] != exp[k]:
                errs.append(f"{where}: {k} {got[k]!r} != {exp[k]!r}")
        if not got["reason"] or exp["reason_contains"] not in got["reason"]:
            errs.append(f"{where}: reason {got['reason']!r} lacks {exp['reason_contains']!r}")
    return max_err


def _match_unordered(exp: list[dict], got: list[dict]) -> list[int] | None:
    """For networks: map expected index -> found index by type and closest length."""
    used: set[int] = set()
    mapping = []
    for e in exp:
        cands = [i for i, g in enumerate(got) if i not in used and g["type"] == e["type"]]
        if not cands:
            return None
        key = "length_m" if "length_m" in e else None
        best = min(cands, key=lambda i: abs(got[i][key] - e[key]) if key else 0)
        used.add(best)
        mapping.append(best)
    return mapping


def compare(expected: dict, graph: SystemGraph) -> tuple[list[str], float]:
    errs: list[str] = []
    got = [c.model_dump() for c in graph.components]
    max_err = 0.0

    if graph.topology != expected["topology"]:
        errs.append(f"topology {graph.topology} != {expected['topology']}")
    if len(got) != expected["component_count"]:
        errs.append(f"component count {len(got)} != {expected['component_count']}")
        return errs, math.nan

    exp_types = [c["type"] for c in expected["components"]]
    if expected["ordered"]:
        if graph.ordered_path != [c["id"] for c in got]:
            errs.append(f"ordered_path {graph.ordered_path} != component order")
        if [g["type"] for g in got] != exp_types:
            errs.append(f"types in order {[g['type'] for g in got]} != {exp_types}")
        mapping = list(range(len(got)))
        if graph.inlet_id != got[0]["id"] or graph.outlet_id != got[-1]["id"]:
            errs.append(f"inlet/outlet {graph.inlet_id}/{graph.outlet_id}")
    else:
        if graph.ordered_path is not None:
            errs.append("ordered_path should be None for a non-line topology")
        if sorted(g["type"] for g in got) != sorted(exp_types):
            errs.append(f"types {sorted(g['type'] for g in got)} != {sorted(exp_types)}")
        m = _match_unordered(expected["components"], got)
        if m is None:
            return [*errs, "could not match components"], math.nan
        mapping = m

    for i, e in enumerate(expected["components"]):
        max_err = max(max_err, _compare_component(e, got[mapping[i]], errs, f"[{i}] {e['type']}"))

    want_edges = {
        frozenset((got[mapping[a]]["id"], got[mapping[b]]["id"])) for a, b in expected["edges"]
    }
    have_edges = {frozenset(e) for e in graph.edges}
    if want_edges != have_edges:
        errs.append(f"edges {sorted(map(sorted, have_edges))} != {sorted(map(sorted, want_edges))}")

    # no double counting: totals
    pipes = sum(g["length_m"] for g in got if g["type"] == "pipe")
    if _rel(pipes, expected["total_pipe_length_m"]) > LEN_REL:
        errs.append(f"total pipe length {pipes:.6f} != {expected['total_pipe_length_m']:.6f}")
    flow = 0.0
    for g in got:
        if g["type"] in ("pipe", "transition"):
            flow += g["length_m"]
        elif g["type"] == "bend":
            flow += g["bend_radius_m"] * math.radians(g["angle_deg"])
    if _rel(flow, expected["total_flow_length_m"]) > LEN_REL:
        errs.append(f"total flow length {flow:.6f} != {expected['total_flow_length_m']:.6f}")

    for w in expected["warnings_contain"]:
        if w not in graph.warnings:
            errs.append(f"missing warning {w!r} in {graph.warnings}")
    return errs, max_err * 100


# --------------------------------------------------------------------------- golden tests
@pytest.mark.parametrize("case", CASES)
def test_golden(case: str, parsed, results) -> None:
    expected = json.loads((GOLDEN / f"{case}.expected.json").read_text())
    out = _parse(parsed, case)
    row = {
        "file": f"{case}.step",
        "expected": expected["component_count"],
        "found": None,
        "max_err": None,
        "seconds": out.seconds,
        "ok": False,
    }
    results.append(row)
    assert isinstance(out.result, SystemGraph), f"parse failed: {out.result}"
    row["found"] = len(out.result.components)
    errs, max_err = compare(expected, out.result)
    row["max_err"] = None if math.isnan(max_err) else max_err
    row["ok"] = not errs
    assert not errs, "\n".join(errs)


@pytest.mark.parametrize("case", CASES)
def test_mesh_leaves_are_components(case: str, parsed) -> None:
    out = _parse(parsed, case)
    assert isinstance(out.result, SystemGraph)
    mesh = out.mesh
    assert mesh is not None
    json.dumps(mesh)  # JSON-serializable, no numpy
    assert mesh["id"] == "/system" and mesh["version"] == 3
    leaf_ids = [p["id"] for p in mesh["parts"]]
    assert leaf_ids == [f"/system/{c.id}" for c in out.result.components]
    for p in mesh["parts"]:
        assert p["name"] == p["id"].rsplit("/", 1)[1]
        shape = p["shape"]
        assert shape["triangles"]["codec"] == "b64" and shape["triangles"]["shape"][0] > 0
        assert shape["vertices"]["dtype"] == "float32"


