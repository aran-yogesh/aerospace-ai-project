def _load_generator():
    spec = importlib.util.spec_from_file_location("golden_generate", GOLDEN / "generate.py")
    assert spec and spec.loader
    mod = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = mod  # dataclasses with postponed annotations need this
    spec.loader.exec_module(mod)
    return mod


def _numbers(graph: SystemGraph) -> list[float]:
    vals = []
    for c in graph.components:
        for k, v in sorted(c.model_dump().items()):
            if isinstance(v, float) and k != "confidence":
                vals.append(v)
    return vals


def test_same_geometry_in_other_units_parses_identically(tmp_path: Path) -> None:
    gen = _load_generator()
    assy, expected = gen.build("07_feed_line")
    outs = {}
    for unit in ("MM", "M", "INCH"):
        path = tmp_path / f"feed_{unit}.step"
        gen.export(assy, path, unit)
        text = path.read_text()
        marker = {"MM": ".MILLI.,.METRE.", "M": "SI_UNIT($,.METRE.)", "INCH": "'INCH'"}[unit]
        assert marker in text, f"{unit} file does not declare its unit"
        out = parse_file(path)
        assert isinstance(out.result, SystemGraph), out.result
        outs[unit] = out.result
    ref = _numbers(outs["MM"])
    for unit in ("M", "INCH"):
        got = _numbers(outs[unit])
        assert len(got) == len(ref)
        for a, b in zip(got, ref, strict=True):
            assert math.isclose(a, b, rel_tol=1e-6, abs_tol=1e-9), (unit, a, b)
    # and the values really are meters
    errs, _ = compare(expected, outs["INCH"])
    assert not errs, errs


