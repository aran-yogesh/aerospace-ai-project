def test_surface_of_revolution_with_circle_profile_is_a_torus() -> None:
    """Some exporters write bends as SURFACE_OF_REVOLUTION; we treat circle profiles as tori."""
    from OCP.BRepBuilderAPI import BRepBuilderAPI_MakeFace
    from OCP.Geom import Geom_Circle, Geom_SurfaceOfRevolution
    from OCP.gp import gp_Ax1, gp_Ax2, gp_Dir, gp_Pnt

    from app.cad_parser.surfaces import Torus, analyze_face

    # tube circle r=6 mm centered 24 mm from a Z axis, revolved 90 deg
    circle = Geom_Circle(gp_Ax2(gp_Pnt(0.024, 0, 0), gp_Dir(0, 1, 0)), 0.006)
    surf = Geom_SurfaceOfRevolution(circle, gp_Ax1(gp_Pnt(0, 0, 0), gp_Dir(0, 0, 1)))
    face = BRepBuilderAPI_MakeFace(surf, 0.0, math.pi / 2, 0.0, 2 * math.pi, 1e-7).Face()
    g = analyze_face(face)
    assert g.kind == "torus" and isinstance(g.surface, Torus)
    assert math.isclose(g.surface.major, 0.024) and math.isclose(g.surface.minor, 0.006)
    assert math.isclose(g.surface.u1 - g.surface.u0, math.pi / 2)
